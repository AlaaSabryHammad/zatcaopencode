#!/usr/bin/env node
/**
 * Pulls design assets from ./design (read-only handoff) into the app so values never drift:
 *  - fonts            → public/fonts/*.woff2
 *  - tokens.css       → src/app/tokens.css         (values unchanged; @font-face removed — next/font loads fonts)
 *  - bundle.css       → src/components/zw/styles/zw-components.css
 *  - ICON_NODES       → src/components/zw/lib/icon-nodes.ts   (Lucide geometry, ISC)
 *  - LOGO paths       → src/components/zw/lib/logo-paths.ts
 *
 * Run with: pnpm icons:sync
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ds = join(root, 'design', 'design-system');
const out = (p) => {
  const f = join(root, p);
  mkdirSync(dirname(f), { recursive: true });
  return f;
};
const header = (src) =>
  `/* AUTO-GENERATED by scripts/sync-design-assets.mjs from ${src} — do not edit by hand. */\n`;

// fonts
for (const f of readdirSync(join(ds, 'fonts'))) {
  if (f.endsWith('.woff2')) copyFileSync(join(ds, 'fonts', f), out(`public/fonts/${f}`));
}

// tokens.css (strip @font-face; next/font/local handles loading)
const tokens = readFileSync(join(ds, 'tokens.css'), 'utf8')
  .split(/\r?\n/)
  .filter((l) => !l.startsWith('@font-face'))
  .join('\n');
writeFileSync(out('src/app/tokens.css'), header('design/design-system/tokens.css') + tokens);

// component css
const css = readFileSync(join(ds, 'components', 'bundle.css'), 'utf8');
writeFileSync(
  out('src/components/zw/styles/zw-components.css'),
  header('design/design-system/components/bundle.css') + css,
);

// icon nodes + logo paths from bundle.js
const js = readFileSync(join(ds, 'components', 'bundle.js'), 'utf8');
const grab = (name) => {
  const line = js.split(/\r?\n/).find((l) => l.startsWith(`var ${name}=`));
  if (!line) throw new Error(`${name} not found in bundle.js`);
  return line.slice(`var ${name}=`.length).replace(/;\s*$/, '');
};
const icons = JSON.parse(grab('ICON_NODES'));
writeFileSync(
  out('src/components/zw/lib/icon-nodes.ts'),
  header('design/design-system/components/bundle.js (ICON_NODES, Lucide — ISC)') +
    `export type IconNode = Array<[string, Record<string, string>]>;\n` +
    `export const ICON_NODES: Record<string, IconNode> = ${JSON.stringify(icons)};\n` +
    `export const ICON_NAMES = Object.keys(ICON_NODES);\n`,
);
const logo = JSON.parse(grab('LOGO'));
writeFileSync(
  out('src/components/zw/lib/logo-paths.ts'),
  header('design/design-system/components/bundle.js (LOGO)') +
    `export const LOGO = ${JSON.stringify(logo)} as const;\n`,
);

console.log(`Synced: ${Object.keys(icons).length} icons, logo paths, tokens, component css, fonts.`);
